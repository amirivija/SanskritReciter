_JS = """
  (function () {
    const players = () => Array.from(document.querySelectorAll('audio.verse-audio'));
    const autoAdv = () => document.getElementById('auto-advance')?.checked;

    function clearPlaying() {
      document.querySelectorAll('.verse.playing').forEach(el => el.classList.remove('playing'));
    }

    players().forEach((audio, idx, all) => {
      audio.addEventListener('play', () => {
        clearPlaying();
        audio.closest('.verse')?.classList.add('playing');
        all.forEach(a => { if (a !== audio) { a.pause(); } });
      });
      audio.addEventListener('ended', () => {
        audio.closest('.verse')?.classList.remove('playing');
        if (!autoAdv()) return;
        const next = all[idx + 1];
        if (next) {
          next.closest('.verse')?.scrollIntoView({ behavior: 'smooth', block: 'center' });
          next.play().catch(() => {});
        }
      });
      audio.addEventListener('pause', () => {
        if (audio.ended) return;
        // keep highlight only while actively playing
        if (audio.currentTime > 0 && !audio.paused) return;
      });
    });

    document.getElementById('btn-play-all')?.addEventListener('click', () => {
      const all = players();
      if (!all.length) return;
      all.forEach(a => { a.pause(); a.currentTime = 0; });
      all[0].closest('.verse')?.scrollIntoView({ behavior: 'smooth', block: 'center' });
      all[0].play().catch(() => {});
    });
    document.getElementById('btn-stop')?.addEventListener('click', () => {
      players().forEach(a => { a.pause(); });
      clearPlaying();
    });
  })();
"""
